// ряд заклёпок/винтов
function rivets(p, n, x0, y, z0, dz, col = K.dsteel, sx = 0.032, size = 0.006) {
  for (let i = 0; i < n; i++) for (const s of [-1, 1]) p.box(0.004, size, size, col, s * sx, y, z0 + i * dz);
}
// кольцо (рифление) вокруг ствола/трубки вдоль Z
function ring(p, r, z, col, y = 0, x = 0, len = 0.006) { p.tz(r, r, len, col, x, y, z, { seg: 12 }); }

